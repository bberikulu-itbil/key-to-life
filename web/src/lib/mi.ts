// The original lists 9 movement items and 11 picture items; its last item repeats the "learning by doing" one, so it counts for movement.
export const miKind = (i: number) => (i < 50 ? Math.floor(i / 10) : i < 59 ? 5 : i < 69 ? 6 : i < 79 ? 7 : i < 89 ? 8 : 5)

/** Each intelligence as 0–100: how far towards "agree" its items were answered. */
export function miScore(ans: (number | null)[]) {
  const sum = Array(9).fill(0), n = Array(9).fill(0)
  ans.forEach((v, i) => { if (v != null) { sum[miKind(i)] += v + 3; n[miKind(i)]++ } })
  return sum.map((s, k) => (n[k] ? Math.round((100 * s) / (6 * n[k])) : 0))
}
