// The Telegram bot's dictionary: i18n-bot.tsv (Kazakh, en, tr, ru — the bot's own texts) + the database texts listed in
// i18n-bot-titles.json, taken from the app dictionaries → supabase/functions/telegram/bot-i18n.ts. Run: node scripts/i18n-bot.cjs
const fs = require('fs'), path = require('path')
const web = (l) => JSON.parse(fs.readFileSync(path.join(__dirname, `../src/i18n/${l}.json`), 'utf8'))
const titles = JSON.parse(fs.readFileSync(path.join(__dirname, 'i18n-bot-titles.json'), 'utf8'))   // every notify() title in the database, and the errors a leave decision can raise
const D = { en: {}, tr: {}, ru: {} }
for (const l of Object.keys(D)) { const w = web(l); for (const k of titles) { if (!w[k]) throw new Error(`${l}: no translation for ${k}`); D[l][k] = w[k] } }
for (const line of fs.readFileSync(path.join(__dirname, 'i18n-bot.tsv'), 'utf8').split('\n').filter(Boolean)) {
  const [k, en, tr, ru] = line.split('\t').map((s) => s.replace(/\\n/g, '\n'))
  Object.assign(D.en, { [k]: en }); Object.assign(D.tr, { [k]: tr }); Object.assign(D.ru, { [k]: ru })
}
const out = `// Generated by web/scripts/i18n-bot.cjs — edit the sources there. Kazakh is the source text.
export type Lang = "kk" | "en" | "tr" | "ru";
export const asLang = (v: unknown): Lang => (v === "en" || v === "tr" || v === "ru" ? v : "kk");
const D: Record<Exclude<Lang, "kk">, Record<string, string>> = ${JSON.stringify(D, null, 1)};

/** Bot text in the reader's language; {0}, {1}… filled from the arguments. */
export function bt(lang: Lang, s: string, ...v: unknown[]) {
  const out = (lang !== "kk" && D[lang][s]) || s;
  return out.replace(/\\{(\\d+)\\}/g, (_, i) => String(v[+i] ?? ""));
}

// notification titles come from the database: an exact text, or a known start followed by a name or title
const STARTS = ["Сіз енді қатысушысыз: ", "Ұсынысыңызға жауап: ", "Рұқсат сұрауы · сынып жетекшісі ", "Сабақтан сұрану "];
export function btTitle(lang: Lang, s: string) {
  if (lang === "kk" || D[lang][s]) return bt(lang, s);
  const p = STARTS.find((x) => s.startsWith(x));
  return p ? bt(lang, p) + s.slice(p.length) : s;
}
`
fs.writeFileSync(path.join(__dirname, '../../supabase/functions/telegram/bot-i18n.ts'), out)
console.log('titles', titles.length, titles[0], '…', titles[titles.length - 1], '| en keys', Object.keys(D.en).length)
